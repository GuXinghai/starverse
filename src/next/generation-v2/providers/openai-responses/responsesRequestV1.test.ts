import { describe, expect, it } from 'vitest'
import { completeOpenAIResponsesRequestV2 } from '../../../../core/generation-v2/providers/openai-responses/continuationArtifactV2'
import { compileOpenAIResponsesRequestV1 } from '../../../../core/generation-v2/providers/openai-responses/responsesRequestV1'

const user = (text: string) => ({ role: 'user', content: [{ type: 'input_text', text }] })

describe('OpenAI Responses V1 exact-body compiler', () => {
  it.each([
    ['png', 'iVBORw0KGgo='], ['jpeg', '/9j/AA=='], ['webp', 'UklGRgAAAABXRUJQ'],
  ])('replays historical %s bytes without a server-side image ID and preserves source artifacts', (format, result) => {
    const image = { id: 'ig_unstored', type: 'image_generation_call', status: 'completed', result, output_format: 'png' }
    const prior = completeOpenAIResponsesRequestV2({ priorArtifact: null, lineageDepth: 1,
      clientItems: [user('draw')], returnedItems: [image] })
    const source = JSON.stringify(prior)
    const next = user('edit it')
    for (const history of [{ priorArtifact: prior, clientItems: [next] }, { replayItems: [user('draw'), image, next] }]) {
      const compiled = compileOpenAIResponsesRequestV1({ model: 'gpt-4.1-mini', ...history })
      expect(compiled.nativeRequest.store).toBe(false)
      expect(compiled.nativeRequest.input).toEqual([user('draw'), { role: 'user', content: [
        { type: 'input_text', text: expect.stringContaining('generated by the assistant') },
        { type: 'input_image', image_url: `data:image/${format};base64,${result}` },
      ] }, next])
      expect(compiled.preparedBody.copyUtf8Text()).not.toContain('ig_unstored')
      expect(compiled.preparedBody.copyUtf8Text()).not.toContain('image_generation_call')
    }
    expect(JSON.stringify(prior)).toBe(source)
  })

  it('retains failed historical image generation as a failure without an ID or image payload', () => {
    const compiled = compileOpenAIResponsesRequestV1({ model: 'gpt-4.1-mini', replayItems: [
      user('draw'), { id: 'ig_failed', type: 'image_generation_call', status: 'failed', result: '' }, user('continue'),
    ] })
    expect(compiled.nativeRequest.input[1]).toEqual(user('[Historical assistant image generation failed; no image output is available.]'))
    expect(compiled.preparedBody.copyUtf8Text()).not.toContain('ig_failed')
  })

  it.each([false, true])('keeps the current masked-edit reference first when historical image matches=%s', sameImage => {
    const result = 'iVBORw0KGgo='
    const targetUrl = sameImage ? `data:image/png;base64,${result}` : 'data:image/jpeg;base64,/9j/AA=='
    const reference = { type: 'input_image', image_url: targetUrl }
    const replayItems = [user('draw'), { id: 'ig_old', type: 'image_generation_call', status: 'completed', result },
      { role: 'user', content: [{ type: 'input_text', text: 'edit this selected image' }, reference] }]
    const source = JSON.stringify(replayItems)
    const compiled = compileOpenAIResponsesRequestV1({ model: 'gpt-4.1-mini', replayItems,
      tools: [{ type: 'image_generation', action: 'edit', inputImageMask: { imageUrl: `data:image/png;base64,${result}` } }],
    })
    const imageInputs = compiled.nativeRequest.input.flatMap(item => 'role' in item && item.role === 'user'
      ? item.content.filter(part => part.type === 'input_image') : [])
    expect(imageInputs[0]).toEqual(reference)
    expect(imageInputs).toHaveLength(sameImage ? 2 : 3)
    expect(compiled.nativeRequest.input.slice(sameImage ? 0 : 1)[0]).toEqual(user('draw'))
    expect(JSON.stringify(replayItems)).toBe(source)
  })

  it.each(['', 'not-base64', 'AAAA', 'iVBORw0KGgp='])('rejects invalid historical image bytes before preparing a request: %s', result => {
    expect(() => compileOpenAIResponsesRequestV1({ model: 'gpt-4.1-mini', replayItems: [
      user('draw'), { id: 'ig_bad', type: 'image_generation_call', status: 'completed', result },
    ] })).toThrow('GENERATION_V2_OPENAI_REQUEST_INVALID_VALUE')
  })

  it('rechecks item limits after adding the masked-edit target anchor', () => {
    const result = 'iVBORw0KGgo='
    const replayItems = [user('first'), { id: 'ig_old', type: 'image_generation_call', status: 'completed', result },
      ...Array.from({ length: 4093 }, () => user('history')),
      { role: 'user', content: [{ type: 'input_image', image_url: 'data:image/jpeg;base64,/9j/AA==' }] }]
    expect(() => compileOpenAIResponsesRequestV1({ model: 'gpt-4.1-mini', replayItems,
      tools: [{ type: 'image_generation', action: 'edit', inputImageMask: { imageUrl: `data:image/png;base64,${result}` } }],
    })).toThrow('GENERATION_V2_OPENAI_NATIVE_ITEM_LIMIT_EXCEEDED')
  })

  it('handles a large valid image without overflowing the base64 validator stack', () => {
    const result = `iVBORw0KGgoA${'AAAA'.repeat(2 * 1024 * 1024)}`
    const compiled = compileOpenAIResponsesRequestV1({ model: 'gpt-4.1-mini', replayItems: [
      user('draw'), { id: 'ig_large', type: 'image_generation_call', status: 'completed', result }, user('continue'),
    ] })
    expect(compiled.nativeRequest.input[1]).toMatchObject({ role: 'user', content: [
      { type: 'input_text' }, { type: 'input_image', image_url: `data:image/png;base64,${result}` },
    ] })
  })

  it('rejects a target anchor that would push duplicated image input beyond the 28 MiB wire budget', () => {
    const result = 'iVBORw0KGgo='
    const replayItems = [user('draw'), { id: 'ig_old', type: 'image_generation_call', status: 'completed', result },
      { role: 'user', content: [{ type: 'input_image', image_url: `data:image/png;base64,${result}${'A'.repeat(14 * 1024 * 1024)}` }] }]
    expect(() => compileOpenAIResponsesRequestV1({ model: 'gpt-4.1-mini', replayItems })).not.toThrow()
    expect(() => compileOpenAIResponsesRequestV1({ model: 'gpt-4.1-mini', replayItems,
      tools: [{ type: 'image_generation', action: 'edit', inputImageMask: { imageUrl: `data:image/png;base64,${result}` } }],
    })).toThrow('GENERATION_V2_OPENAI_NATIVE_ITEM_LIMIT_EXCEEDED')
  })

  it('keeps incomplete wire reasoning out of explicit replay without changing the source facts', () => {
    const replayItems = [user('first'),
      { id: 'absent', type: 'reasoning', summary: [] },
      { id: 'null', type: 'reasoning', summary: [], encrypted_content: null },
      { id: 'empty', type: 'reasoning', summary: [], encrypted_content: '' },
      { id: 'partial', type: 'reasoning', summary: [], encrypted_content: 'partial', status: 'incomplete' },
      { id: 'complete', type: 'reasoning', summary: [], encrypted_content: 'opaque' }, user('next')]
    const source = JSON.stringify(replayItems)
    const result = compileOpenAIResponsesRequestV1({ model: 'gpt-6-luna', replayItems })
    expect(result.nativeRequest.input).toEqual([replayItems[0], replayItems[5], replayItems[6]])
    expect(result.nativeRequest).toMatchObject({ store: false, include: ['reasoning.encrypted_content'] })
    expect(JSON.stringify(replayItems)).toBe(source)
  })
  it('compiles stateless streaming with complete supported semantic fields and no hidden fallback', () => {
    const result = compileOpenAIResponsesRequestV1({
      model: 'gpt-5.4', priorArtifact: null, clientItems: [user('draw and research')],
      instructions: 'Be concise.',
      reasoning: { effort: 'medium', summary: 'detailed' },
      generation: { temperature: 0.4, topP: 0.8, maxOutputTokens: 2048, verbosity: 'low' },
      tools: [
        { type: 'function', name: 'weather', description: 'Weather', parameters: { type: 'object', properties: {} }, strict: true },
        { type: 'web_search', searchContextSize: 'medium', allowedDomains: ['example.com'] },
        { type: 'image_generation', action: 'auto', size: '1024x1024', quality: 'low', outputFormat: 'png', background: 'opaque', partialImages: 2 },
      ],
      toolChoice: 'auto',
      maxToolCalls: 8,
      parallelToolCalls: false,
      serviceTier: 'default',
    })
    expect(result.nativeRequest).toEqual({
      model: 'gpt-5.4', input: [user('draw and research')], stream: true, store: false,
      include: ['reasoning.encrypted_content'], instructions: 'Be concise.',
      reasoning: { effort: 'medium', summary: 'detailed' },
      temperature: 0.4, top_p: 0.8, max_output_tokens: 2048, text: { verbosity: 'low' },
      tools: [
        { type: 'function', name: 'weather', description: 'Weather', parameters: { properties: {}, type: 'object' }, strict: true },
        { type: 'web_search', search_context_size: 'medium', filters: { allowed_domains: ['example.com'] } },
        { type: 'image_generation', action: 'auto', size: '1024x1024', quality: 'low', output_format: 'png', background: 'opaque', partial_images: 2 },
      ],
      tool_choice: 'auto',
      max_tool_calls: 8,
      parallel_tool_calls: false,
      service_tier: 'default',
    })
    const exact = JSON.parse(result.preparedBody.copyUtf8Text())
    expect(exact).toEqual(result.nativeRequest)
    expect(exact).not.toHaveProperty('previous_response_id')
    expect(exact).not.toHaveProperty('conversation')
  })

  it('replays prior native reasoning, tool call and output byte-for-byte in input order', () => {
    const prior = completeOpenAIResponsesRequestV2({
      priorArtifact: null, lineageDepth: 1, clientItems: [user('weather?')],
      returnedItems: [
        { id: 'rs_1', type: 'reasoning', status: 'completed', summary: [], encrypted_content: 'encrypted' },
        { id: 'fc_1', type: 'function_call', call_id: 'call_1', name: 'weather', arguments: '{}', status: 'completed' },
      ],
    })
    const result = compileOpenAIResponsesRequestV1({
      model: 'gpt-5.4', priorArtifact: prior,
      clientItems: [{ type: 'function_call_output', call_id: 'call_1', output: 'sunny' }],
    })
    expect(result.nativeRequest.input).toEqual([
      user('weather?'),
      { id: 'rs_1', type: 'reasoning', status: 'completed', summary: [], encrypted_content: 'encrypted' },
      { id: 'fc_1', type: 'function_call', call_id: 'call_1', name: 'weather', arguments: '{}', status: 'completed' },
      { type: 'function_call_output', call_id: 'call_1', output: 'sunny' },
    ])
  })

  it('accepts an explicit selected-turn replay without manufacturing a continuation artifact', () => {
    const replayItems = [
      user('first'),
      { id: 'rs_1', type: 'reasoning', status: 'completed', summary: [], encrypted_content: 'encrypted' },
      { id: 'msg_1', type: 'message', role: 'assistant', status: 'completed', content: [{ type: 'output_text', text: 'one', annotations: [] }] },
      user('third'),
    ]
    const result = compileOpenAIResponsesRequestV1({ model: 'gpt-5.4', replayItems })
    expect(result.nativeRequest.input).toEqual(replayItems)
    expect(result.nativeRequest).not.toHaveProperty('previous_response_id')
    expect(() => compileOpenAIResponsesRequestV1({
      model: 'gpt-5.4', replayItems, priorArtifact: null, clientItems: [user('ignored')],
    })).toThrow('GENERATION_V2_OPENAI_REQUEST_INVALID_SHAPE')
  })

  it('encodes a persisted OpenAI Files identifier as input_file without a data URL fallback', () => {
    const result = compileOpenAIResponsesRequestV1({
      model: 'gpt-5.6-sol', priorArtifact: null,
      clientItems: [{
        role: 'user', content: [
          { type: 'input_text', text: 'summarize the attachment' },
          { type: 'input_file', file_id: 'file_abc123' },
        ],
      }],
    })
    expect(result.nativeRequest.input).toEqual([{
      role: 'user', content: [
        { type: 'input_text', text: 'summarize the attachment' },
        { type: 'input_file', file_id: 'file_abc123' },
      ],
    }])
    expect(result.preparedBody.copyUtf8Text()).not.toContain('data:')
  })

  it('encodes the maximum reasoning effort without aliasing it', () => {
    const result = compileOpenAIResponsesRequestV1({
      model: 'gpt-5.6-sol', priorArtifact: null, clientItems: [user('x')],
      reasoning: { effort: 'max', summary: 'auto' },
    })
    expect(result.nativeRequest.reasoning).toEqual({ effort: 'max', summary: 'auto' })
  })

  it('encodes GPT-5.6 reasoning mode and persisted context in the exact body', () => {
    const result = compileOpenAIResponsesRequestV1({
      model: 'gpt-5.6-sol', priorArtifact: null, clientItems: [user('x')],
      reasoning: { effort: 'max', summary: 'auto', mode: 'pro', context: 'all_turns' },
    })
    expect(result.nativeRequest.reasoning).toEqual({ effort: 'max', summary: 'auto', mode: 'pro', context: 'all_turns' })
    expect(JSON.parse(result.preparedBody.copyUtf8Text()).reasoning).toEqual(result.nativeRequest.reasoning)
  })

  it('preserves input_image file_id and URL forms alongside input_file', () => {
    const result = compileOpenAIResponsesRequestV1({
      model: 'gpt-5.6-sol', priorArtifact: null,
      clientItems: [{ role: 'user', content: [
        { type: 'input_image', file_id: 'file_image_1', detail: 'high' },
        { type: 'input_image', image_url: 'https://example.test/image.png', detail: 'auto' },
        { type: 'input_file', file_id: 'file_pdf_1' },
      ] }],
    })
    expect(result.nativeRequest.input[0]).toEqual({ role: 'user', content: [
      { type: 'input_image', file_id: 'file_image_1', detail: 'high' },
      { type: 'input_image', image_url: 'https://example.test/image.png', detail: 'auto' },
      { type: 'input_file', file_id: 'file_pdf_1' },
    ] })
  })

  it('encodes a named function tool choice only when the exact function is present', () => {
    const result = compileOpenAIResponsesRequestV1({
      model: 'gpt-5.6-sol', priorArtifact: null, clientItems: [user('weather?')],
      tools: [{ type: 'function', name: 'weather', parameters: { type: 'object' }, strict: false }],
      toolChoice: { type: 'function', name: 'weather' },
    })
    expect(result.nativeRequest.tool_choice).toEqual({ type: 'function', name: 'weather' })
    expect(() => compileOpenAIResponsesRequestV1({
      model: 'gpt-5.6-sol', priorArtifact: null, clientItems: [user('weather?')],
      tools: [{ type: 'function', name: 'weather', parameters: { type: 'object' }, strict: false }],
      toolChoice: { type: 'function', name: 'unknown' },
    })).toThrow('GENERATION_V2_OPENAI_REQUEST_INVALID_VALUE')
  })

  it('rejects invalid reasoning values, unsafe tool schemas and invalid explicit choices', () => {
    expect(() => compileOpenAIResponsesRequestV1({
      model: 'gpt-5.4', priorArtifact: null, clientItems: [user('x')], reasoning: { effort: 'medium', mode: 'invalid' },
    })).toThrow('GENERATION_V2_OPENAI_REQUEST_INVALID_VALUE')
    expect(() => compileOpenAIResponsesRequestV1({
      model: 'gpt-5.4', priorArtifact: null, clientItems: [user('x')],
      tools: [{ type: 'function', name: 'x', parameters: { get value() { return 'x' } }, strict: true }],
    })).toThrow('GENERATION_V2_OPENAI_REQUEST_INVALID_VALUE')
    expect(() => compileOpenAIResponsesRequestV1({
      model: 'gpt-5.4', priorArtifact: null, clientItems: [user('x')], toolChoice: 'required',
    })).toThrow('GENERATION_V2_OPENAI_REQUEST_INVALID_VALUE')
    expect(() => compileOpenAIResponsesRequestV1({
      model: 'gpt-5.4', priorArtifact: null, clientItems: [user('x')], previous_response_id: 'resp_1',
    })).toThrow('GENERATION_V2_OPENAI_REQUEST_UNKNOWN_FIELD')
  })
})
