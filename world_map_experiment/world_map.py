def P(*v):
    """把扁平数字序列转成 [(lon,lat), ...]."""
    return list(zip(v[0::2], v[1::2]))


def in_poly(lon, lat, poly):
    """射线法点在多边形内。多边形经度可超出 ±180 (跨日界线的图形这样表达)。"""
    n = len(poly)
    cx = sum(p[0] for p in poly) / n
    x = lon
    while x - cx > 180:
        x -= 360
    while cx - x > 180:
        x += 360
    ins = False
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > lat) != (yj > lat) and x < xi + (lat - yi) * (xj - xi) / (yj - yi):
            ins = not ins
        j = i
    return ins


def in_any(lon, lat, polys):
    return any(in_poly(lon, lat, p) for p in polys)


