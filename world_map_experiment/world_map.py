def ant_coast_lat(lon):
    x = lon % 360
    for i in range(1, len(ANT_COAST)):
        if x <= ANT_COAST[i][0]:
            (x0, y0), (x1, y1) = ANT_COAST[i - 1], ANT_COAST[i]
            return y0 + (y1 - y0) * ((x - x0) / (x1 - x0) if x1 > x0 else 0)
    return -70.0


